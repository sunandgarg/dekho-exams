package in.aitrove.contracts;

import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.MapSqlParameterSource;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.core.simple.SimpleJdbcInsert;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import static org.junit.jupiter.api.Assertions.*;

public class JdbcParametersAndKeysContractTest {
    @Test void namedCollectionParameterKeepsTenantPredicateInTheQuery() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:named_receipts;DB_CLOSE_DELAY=-1", "sa", "");
        var jdbc = new JdbcTemplate(source);
        jdbc.execute("drop table if exists receipt_route");
        jdbc.execute("create table receipt_route (receipt_id bigint primary key, tenant_id varchar(32), region varchar(32))");
        jdbc.update("insert into receipt_route values (?,?,?)", 47L, "TENANT-A", "WEST");
        jdbc.update("insert into receipt_route values (?,?,?)", 82L, "TENANT-B", "EAST");
        jdbc.update("insert into receipt_route values (?,?,?)", 91L, "TENANT-A", "NORTH");

        List<Long> selectedIds = List.of(47L, 82L, 91L);
        var parameters = new MapSqlParameterSource()
                .addValue("tenantId", "TENANT-A")
                .addValue("receiptIds", selectedIds);
        var named = new NamedParameterJdbcTemplate(source);
        var matches = named.queryForList(
                "select receipt_id from receipt_route where tenant_id = :tenantId " +
                "and receipt_id in (:receiptIds) order by receipt_id",
                parameters, Long.class);
        assertEquals(List.of(47L, 91L), matches);
    }

    @Test void generatedKeyIsReadFromTheDatabaseInsertResult() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:insert_receipts;DB_CLOSE_DELAY=-1", "sa", "");
        var jdbc = new JdbcTemplate(source);
        jdbc.execute("drop table if exists receipt_entry");
        jdbc.execute("create table receipt_entry (id bigint generated by default as identity primary key, " +
                "tenant_id varchar(32) not null, amount_cents bigint not null)");

        var insert = new SimpleJdbcInsert(source)
                .withTableName("receipt_entry")
                .usingColumns("tenant_id", "amount_cents")
                .usingGeneratedKeyColumns("id");
        Number generatedId = insert.executeAndReturnKey(
                Map.of("tenant_id", "TENANT-A", "amount_cents", 4725L));
        assertEquals(4725L, jdbc.queryForObject(
                "select amount_cents from receipt_entry where id = ?", Long.class,
                generatedId.longValue()));
        assertEquals(1, jdbc.queryForObject("select count(*) from receipt_entry", Integer.class));
    }
}
